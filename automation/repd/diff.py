#!/usr/bin/env python3
"""automation/repd/diff.py - REPD release-over-release change report.

    python -m automation.repd.diff --previous PREV --new NEW --out DIR \
        [--previous-label "July 2026 (Q2)"] [--new-label "October 2026 (Q3)"] \
        [--capacity-tolerance 0.0051] [--protect PATH ...]

PREV  either an official-layout REPD CSV (53 columns, utf-8-sig or cp1252)
      or the derived globalgrid2050 dist/project_identity_v6.json (all records,
      ~20 of the 53 official columns; only those columns are compared).
NEW   the cleaned canonical CSV from clean.py (official 53-column layout;
      dd/mm/yyyy or ISO dates). An official raw CSV also works.

Writes DIR/changelog.md (concise, human-readable) and DIR/diff.json (full lists).
Both are deterministic: stable ordering, no timestamps, no absolute paths, so they can
be committed and re-generated byte-identically. Inputs are identified by file name,
size and sha256 only.

Conventions (repeated in the outputs):
  * Comparison basis is unique Ref IDs; where a Ref ID repeats, the first row is kept
    and the duplicate is reported (identical or conflicting).
  * Capacity = "Installed Capacity (MWelec)". Blank / non-numeric = UNKNOWN, never zero:
    MW totals sum known capacities only and carry the unknown count alongside.
  * A capacity edit is |new - old| > --capacity-tolerance (default 0.0051 MW) so that a
    2-decimal CSV compared with an Excel-precision file does not report rounding noise.
  * Milestone categories (status-based, as in the July->October prototype):
      newly consented          new status Awaiting Construction, previous status not
                               Awaiting Construction / Under Construction / Operational
      newly under construction new Under Construction, previous not Under Construction / Operational
      newly operational        new Operational, previous not Operational
      newly refused            new Application Refused / Appeal Refused, previous not refused
      newly withdrawn          new Application Withdrawn / Appeal Withdrawn, previous not withdrawn
    "transition" = ref in both releases whose status moved; "new record" = ref absent
    from the previous release that first appears already in that status. MW = new capacity.

Hash guard ("no truncation of previous work"): the inputs and every --protect path
(file or directory, recursively) are sha256-hashed before and after the run; the run
fails (exit 3) if any differs, and refuses an --out directory inside a protected path.

Standard library only. No network.
"""
