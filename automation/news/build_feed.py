#!/usr/bin/env python3
"""automation/news/build_feed.py - build the REPD events feed, the article relevance file and the
binder evaluation for one release pair. Every output is NEW (never an existing feed name) and
deterministic (no clock, no absolute paths; inputs by name, size and sha256).

    python -m automation.news.build_feed \
        --previous REPD_Q2_2026_cleaned.csv --previous-label "July 2026 (Q2)" \
        --new repd-2026q3.csv --new-label "October 2026 (Q3)" --release 2026q3 \
        --previous-feed dist/major_project_news_v9_5_1.json \
        --convergence dist/convergence/2026q3 \
        --datacentres uk_datacentre_pipeline_202610312133.geojson \
        --labels automation/news/labels/binding_labels_v9_5_1.json \
        --out-dir dist/news --docs-dir docs/news/2026q3

Writes
  <out-dir>/repd_events_<release>.json           schema globalgrid2050.pipeline-news.repd-events-feed.v1
  <out-dir>/repd_events_<release>_top50.csv      the top 50 (co-located siblings folded)
  <out-dir>/article_relevance_v9_5_1_<release>.json   the 133 v9.5.1 articles re-bound and re-scored
  <out-dir>/binder_evaluation_v9_5_1.json        binder metrics on the labelled set
  <docs-dir>/top50.md                            the top 50 as a readable table

Aggregate open-data facts only; headlines are generated from REPD fields; no commentary on
companies. Proximity to data centres is straight-line screening, never a connection.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from datetime import date
from pathlib import Path

from automation.repd import diff as repd
from automation.news import events as E
from automation.news import relevance as R
from automation.news import binder as B

FEED_SCHEMA = "globalgrid2050.pipeline-news.repd-events-feed.v1"
ARTICLES_SCHEMA = "globalgrid2050.pipeline-news.article-relevance.v1"
TOP_N = 50
CAVEATS = [
    "Events are derived from two official DESNZ REPD releases; a REPD status change records when the "
    "register was updated, which can lag the real-world decision.",
    "Blank REPD capacity is unknown (null), never zero.",
    "Headlines are generated from REPD fields only; they carry no commentary on any company.",
    "Data-centre proximity is straight-line screening from the convergence join; it is not a grid "
    "connection, capacity, offtake or planning link. Data centres are a separate category and never "
    "carry a REPD Ref ID.",
    "Relevance is an additive, rule-based score for a solar, storage and grid business; every component "
    "is shown and the profile is versioned.",
]


LANE = "REPD_EVENTS"


def panel_fields(ev: dict) -> dict:
    """Flat fields shared with the data-centre capex/politics panel (N4): title, date, link or ref, lane,
    score. link is null (REPD has no article URL); ref and gg_project_id identify the project."""
    return {"title": ev["headline"], "date": ev["event_date"] or ev["record_last_updated"],
            "date_kind": "milestone" if ev["event_date"] else "record_last_updated",
            "link": None, "lane": LANE, "score": ev["relevance"]["score"]}


def _input(role, path, label=None, extra=None):
    p = Path(path)
    out = {"role": role, "file": label or p.name, "bytes": p.stat().st_size, "sha256": R.sha256_file(p)}
    out.update(extra or {})
    return out


def _dump(path: Path, doc) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def top50_csv(top: list) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["rank", "score", "event_type", "ref", "grouped_refs", "site_name", "technology", "capacity_mw",
                "previous_status", "status", "county", "region", "country", "event_date", "headline",
                "nearest_datacentre_km", "event_id"])
    for ev in top:
        near = ((ev.get("datacentre_context") or {}).get("nearest") or {})
        w.writerow([ev["top_rank"], ev["relevance"]["score"], ev["event_type"], ev["ref"], " ".join(ev["grouped_refs"]),
                    ev["site_name"], ev["technology"] or "", "" if ev["capacity_mw"] is None else ev["capacity_mw"],
                    ev["previous_status"] or "", ev["status"] or "", ev["county"] or "", ev["region"] or "",
                    ev["country"] or "", ev["event_date"] or "", ev["headline"],
                    "" if near.get("km") is None else near["km"], ev["event_id"]])
    return buf.getvalue()


def top50_md(feed: dict) -> str:
    lines = [f"# Pipeline News: top {len(feed['top'])} REPD project events, {feed['previous']['label']} to {feed['new']['label']}",
             "",
             f"Generated by `{feed['tool']}` from `{feed['previous']['file']}` (sha256 `{feed['previous']['sha256'][:16]}…`) and "
             f"`{feed['new']['file']}` (sha256 `{feed['new']['sha256'][:16]}…`). Relevance profile `{feed['profile']['id']}` "
             f"(sha256 `{feed['profile_sha256'][:16]}…`), reference date {feed['reference_date']}. Score out of "
             f"{feed['max_score']:g}; components: capacity, stage, technology, recency, national route, data-centre "
             "proximity, novelty, evidence tier, co-located storage. Full components per event in "
             f"`dist/news/repd_events_{feed['release']}.json`.",
             "",
             "Open data only (DESNZ REPD; data-centre proximity from the convergence join is screening, not a connection).",
             "",
             "| # | Score | Event | REPD | MW | Technology | Place | Headline |",
             "|---|---|---|---|---|---|---|---|"]
    for ev in feed["top"]:
        refs = ev["ref"] + (f" (+{', '.join(ev['grouped_refs'])})" if ev["grouped_refs"] else "")
        mw = "unknown" if ev["capacity_mw"] is None else f"{ev['capacity_mw']:g}"
        place = ev["county"] or ev["region"] or ""
        lines.append(f"| {ev['top_rank']} | {ev['relevance']['score']:g} | {ev['event_type']} | {refs} | {mw} | "
                     f"{ev['technology'] or ''} | {place} | {ev['headline'].replace('|', '/')} |")
    lines += ["", "Counts by event type (all events, before ranking):", ""]
    lines += [f"- {k}: {v}" for k, v in feed["counts"].items() if v]
    return "\n".join(lines) + "\n"


def build(a) -> dict:
    old, new = E.load_pair(a.previous, a.new)
    ev_doc = E.build_events(old, new, a.previous_label, a.new_label, a.large_application_mw)
    reference = date.fromisoformat(new["info"]["max_record_last_updated"])
    dc_index = R.load_datacentre_index(a.convergence) if a.convergence else None
    previous = R.load_previous_feed(a.previous_feed) if a.previous_feed else None
    ranked = R.rank_events(ev_doc["events"], reference, dc_index, previous)
    for ev in ranked:
        ev.update(panel_fields(ev))
    top_ids = R.top_events(ranked, TOP_N)
    by_id = {e["event_id"]: e for e in ranked}
    top = []
    for t in top_ids:
        ev = dict(by_id[t["event_id"]])
        ev["top_rank"] = t["rank"]
        ev["grouped_refs"] = t["grouped_refs"]
        top.append(ev)

    inputs = [
        {"role": "repd_previous", **{k: ev_doc["previous"][k] for k in ("file", "bytes", "sha256", "unique_refs")}},
        {"role": "repd_new", **{k: ev_doc["new"][k] for k in ("file", "bytes", "sha256", "unique_refs")}},
    ]
    if previous:
        inputs.append(_input("previous_feed", a.previous_feed, f"dist/{Path(a.previous_feed).name}"))
    inputs += [{"role": "convergence", **x} for x in R.convergence_inputs(a.convergence)]

    feed = {
        "schema": FEED_SCHEMA,
        "tool": "automation/news/build_feed.py",
        "release": a.release,
        "category": "REPD_ENERGY_PROJECTS",
        "lane": LANE,
        "panel_fields": ["title", "date", "link", "ref", "lane", "score"],
        "previous": ev_doc["previous"],
        "new": ev_doc["new"],
        "reference_date": reference.isoformat(),
        "reference_date_rule": "newest Record Last Updated in the new release (no wall clock)",
        "inputs": inputs,
        "profile": R.DEFAULT_PROFILE,
        "profile_sha256": R.profile_sha256(),
        "max_score": R.max_possible(),
        "rules": ev_doc["rules"],
        "datacentre_join": "supplied" if dc_index is not None else "not supplied",
        "caveats": CAVEATS,
        "counts": ev_doc["counts"],
        "operator_cosmetic_changes_not_emitted": ev_doc["operator_cosmetic_changes_not_emitted"],
        "event_count": len(ranked),
        "top_n": TOP_N,
        "top": top,
        "events": ranked,
    }

    # ---- articles: re-bind and re-score the v9.5.1 newspaper against the new register
    index = B.ProjectIndex(new)
    dci = B.DatacentreIndex(a.datacentres) if a.datacentres else None
    release_events_by_ref = {}
    for ev in ranked:
        release_events_by_ref.setdefault(ev["ref"], set()).add(ev["event_type"])
    articles_out = None
    if a.previous_feed:
        legacy = json.loads(Path(a.previous_feed).read_text(encoding="utf-8"))
        art_ref = date.fromisoformat(str(legacy.get("updated", reference.isoformat()))[:10])
        rows = []
        for i, it in enumerate(legacy.get("all_items", [])):
            art = {"headline": it.get("headline"), "source": it.get("source", ""), "source_url": it.get("source_url", ""),
                   "url": it.get("url"), "published": it.get("published")}
            b = B.bind(art, index)
            project = index.records.get(b["ref"]) if b["ref"] and b["class"] in B.SIGNAL_CLASSES else None
            rel = R.score_article(art, b, project, art_ref, dc_index, None, release_events_by_ref)
            row = {"id": f"v951-{i:03d}", "gg_article_id": it.get("gg_article_id"), **art,
                   "category": "DATA_CENTRES" if dci and dci.bind(art)["topic_datacentres"] else "ENERGY",
                   "binding": {k: b[k] for k in ("class", "ref", "gg_project_id", "related_refs", "evidence", "trace")},
                   "drives_project_signal": b["class"] in B.SIGNAL_CLASSES,
                   "legacy_v9_5_1": {"role": it.get("role"), "repd_ref": it.get("repd_ref"), "event": it.get("event"),
                                     "confidence": it.get("confidence")},
                   "relevance": rel}
            if dci:
                row["datacentre_binding"] = dci.bind(art)
            rows.append(row)
        # dedupe: one lead story per (bound development, article event); official first, then earliest
        clusters = {}
        for row in rows:
            if not row["drives_project_signal"]:
                continue
            grp = index.records[row["binding"]["ref"]]["group"]
            clusters.setdefault((grp, row["relevance"]["article_event"]), []).append(row)
        tier_rank = {"official_record": 0, "attributed_reporting": 1, "unverified_lead": 2}
        for members in clusters.values():
            members.sort(key=lambda r: (tier_rank[r["relevance"]["evidence_tier"]], r["published"] or "", r["id"]))
            for m in members[1:]:
                m["duplicate_of"] = members[0]["id"]
        rows.sort(key=lambda r: (-r["relevance"]["score"], r["id"]))
        for k, row in enumerate(rows, 1):
            row["rank"] = k
        articles_out = {
            "schema": ARTICLES_SCHEMA,
            "tool": "automation/news/build_feed.py",
            "release": a.release,
            "reference_date": art_ref.isoformat(),
            "reference_date_rule": "the legacy feed's own 'updated' date (scores do not drift with the clock)",
            "inputs": inputs[:2] + [x for x in inputs if x["role"] == "previous_feed"] +
                      ([_input("datacentre_register", a.datacentres)] if a.datacentres else []),
            "profile_sha256": R.profile_sha256(),
            "max_score": R.max_possible(article=True),
            "note": "The v9.5.1 articles (Aug 2026 crawl) re-bound to October 2026 REPD Ref IDs and re-scored; "
                    "novelty is not assessed against the feed the articles came from.",
            "counts": {
                "articles": len(rows),
                "by_binding_class": {c: sum(1 for r in rows if r["binding"]["class"] == c) for c in B.CLASS_ORDER},
                "drives_project_signal": sum(1 for r in rows if r["drives_project_signal"]),
                "duplicates_folded": sum(1 for r in rows if r.get("duplicate_of")),
                "by_evidence_tier": {t: sum(1 for r in rows if r["relevance"]["evidence_tier"] == t) for t in tier_rank},
                "category_datacentres": sum(1 for r in rows if r["category"] == "DATA_CENTRES"),
                "datacentre_site_bindings": sum(len(r.get("datacentre_binding", {}).get("bindings", [])) for r in rows),
                "contradictions": sum(1 for r in rows if r["relevance"]["contradiction"]),
                "officially_corroborated_in_release": sum(1 for r in rows if any(
                    c["name"] == "official_corroboration" and c["points"] == R.DEFAULT_PROFILE["official_corroboration"]["same_event_in_release"]
                    for c in r["relevance"]["components"])),
            },
            "articles": rows,
        }

    evaluation = None
    if a.labels:
        labels_doc = json.loads(Path(a.labels).read_text(encoding="utf-8"))
        evaluation = B.evaluate(labels_doc["labels"], index)
        evaluation["inputs"] = [inputs[1], _input("labels", a.labels, "automation/news/labels/" + Path(a.labels).name)]
        evaluation["labels_method"] = labels_doc.get("method")
    return {"feed": feed, "articles": articles_out, "evaluation": evaluation}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--previous", required=True)
    ap.add_argument("--new", required=True)
    ap.add_argument("--previous-label", default="previous")
    ap.add_argument("--new-label", default="new")
    ap.add_argument("--release", required=True)
    ap.add_argument("--previous-feed")
    ap.add_argument("--convergence")
    ap.add_argument("--datacentres")
    ap.add_argument("--labels")
    ap.add_argument("--large-application-mw", type=float, default=E.DEFAULT_LARGE_APPLICATION_MW)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--docs-dir")
    a = ap.parse_args(argv)
    out = build(a)
    od = Path(a.out_dir)
    feed_path = od / f"repd_events_{a.release}.json"
    for p in (feed_path,):
        if p.exists() and p.read_text(encoding="utf-8") != json.dumps(out["feed"], indent=1, ensure_ascii=False) + "\n":
            print(f"note: {p} exists and will be replaced by this build's bytes", file=sys.stderr)
    _dump(feed_path, out["feed"])
    (od / f"repd_events_{a.release}_top50.csv").write_text(top50_csv(out["feed"]["top"]), encoding="utf-8")
    if out["articles"]:
        _dump(od / f"article_relevance_v9_5_1_{a.release}.json", out["articles"])
    if out["evaluation"]:
        _dump(od / "binder_evaluation_v9_5_1.json", out["evaluation"])
    if a.docs_dir:
        dd = Path(a.docs_dir)
        dd.mkdir(parents=True, exist_ok=True)
        (dd / "top50.md").write_text(top50_md(out["feed"]), encoding="utf-8")
    summary = {"events": out["feed"]["event_count"], "counts": out["feed"]["counts"]}
    if out["evaluation"]:
        summary["binder_signal"] = out["evaluation"]["signal_metrics"]
    print(json.dumps(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
