# --------------------------------------------------------------------------- hash guard

def hash_paths(paths) -> dict:
    """{path: sha256} for every file under each path (files or directories), sorted."""
    out = {}
    for p in paths:
        p = Path(p)
        if p.is_dir():
            for root, dirs, files in os.walk(p):
                dirs[:] = sorted(x for x in dirs if x != ".git")
                for f in sorted(files):
                    fp = Path(root) / f
                    out[str(fp)] = sha256_file(fp)
        elif p.is_file():
            out[str(p)] = sha256_file(p)
        else:
            raise DiffError(f"protected path does not exist: {p}")
    return dict(sorted(out.items()))


def compare_hashes(before: dict, after: dict) -> list:
    problems = []
    for k in sorted(set(before) | set(after)):
        if k not in after:
            problems.append(f"deleted: {k}")
        elif k not in before:
            problems.append(f"created: {k}")
        elif before[k] != after[k]:
            problems.append(f"modified: {k}")
    return problems


def _inside(child: Path, parent: Path) -> bool:
    try:
        child.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


# --------------------------------------------------------------------------- run

def run(previous, new, out_dir, previous_label="previous", new_label="new",
        cap_tol=DEFAULT_CAP_TOL, protect=()) -> dict:
    out = Path(out_dir)
    protected = [Path(previous), Path(new)] + [Path(p) for p in protect]
    for p in protected:
        if p.is_dir() and _inside(out, p):
            raise DiffError(f"--out {out} is inside protected path {p}; choose another directory")
        for name in ("diff.json", "changelog.md"):
            if p.is_file() and (out / name).resolve() == p.resolve():
                raise DiffError(f"--out would overwrite protected file {p}")
    before = hash_paths(protected)
    new_snap = load_csv(new)
    old_snap = load_previous(previous, header_reference=new_snap["header"])
    d = build_diff(old_snap, new_snap, previous_label, new_label, cap_tol)
    md = render_md(d)
    out.mkdir(parents=True, exist_ok=True)
    (out / "diff.json").write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "changelog.md").write_text(md, encoding="utf-8")
    problems = compare_hashes(before, hash_paths(protected))
    if problems:
        raise DiffError("hash guard: protected files changed during the run: " + "; ".join(problems))
    d["_hash_guard"] = {"protected_files": len(before), "unchanged": True}
    return d


def run_from_descriptor(desc: dict) -> dict:
    """Release-descriptor entry point. Keys: previous, new, out, previous_label, label,
    capacity_tolerance (optional), protect (optional list)."""
    for k in ("previous", "new", "out"):
        if not desc.get(k):
            raise DiffError(f"release descriptor lacks '{k}'")
    return run(desc["previous"], desc["new"], desc["out"], desc.get("previous_label", "previous"),
               desc.get("label", "new"), float(desc.get("capacity_tolerance", DEFAULT_CAP_TOL)),
               desc.get("protect", ()))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="REPD release-over-release change report.")
    ap.add_argument("--previous", required=True, help="official-layout CSV or project_identity_v6.json")
    ap.add_argument("--new", required=True, help="cleaned canonical CSV")
    ap.add_argument("--out", required=True, help="output directory (changelog.md, diff.json)")
    ap.add_argument("--previous-label", default="previous")
    ap.add_argument("--new-label", default="new")
    ap.add_argument("--capacity-tolerance", type=float, default=DEFAULT_CAP_TOL)
    ap.add_argument("--protect", action="append", default=[],
                    help="file or directory that must be byte-identical after the run (repeatable)")
    args = ap.parse_args(argv)
    try:
        d = run(args.previous, args.new, args.out, args.previous_label, args.new_label,
                args.capacity_tolerance, args.protect)
    except DiffError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 3 if str(exc).startswith("hash guard") else 2
    s = d["summary"]
    print(f"{d['previous']['label']}: {s['previous_refs']} refs; {d['new']['label']}: {s['new_refs']} refs")
    print(f"added {s['added']} ({s['added_mw']} MW), removed {s['removed']} ({s['removed_mw']} MW), "
          f"retained {s['retained']}; status changes {s['status_changes']}; "
          f"capacity edits {s['capacity_edits']} (net {s['capacity_edits_net_mw']} MW)")
    print("milestones: " + ", ".join(f"{k} {v['n']} / {v['mw']} MW" for k, v in s["milestones"].items()))
    print(f"hash guard: {d['_hash_guard']['protected_files']} protected files unchanged")
    print(f"wrote {Path(args.out) / 'changelog.md'} and {Path(args.out) / 'diff.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
